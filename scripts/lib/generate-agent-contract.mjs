import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Generate the public agent-tool contract from the MCP server's actual
 * tools/list response.
 *
 * @param {{ cli: string, root: string, version: string }} options
 */
export async function generateAgentContract(options) {
  const child = spawn(process.execPath, [options.cli, "mcp"], {
    cwd: options.root,
    env: { ...process.env, ADB_READY_INTERACTIVE: "false", NO_COLOR: "1" },
    shell: false,
    stdio: ["pipe", "pipe", "pipe"],
    windowsHide: true,
  });
  let stdout = "";
  let stderr = "";
  let closedInput = false;
  const requests = [
    {
      jsonrpc: "2.0",
      id: 1,
      method: "initialize",
      params: {
        protocolVersion: "2025-11-25",
        capabilities: {},
        clientInfo: { name: "adb-ready-contract-generator", version: "1" },
      },
    },
    { jsonrpc: "2.0", method: "notifications/initialized" },
    { jsonrpc: "2.0", id: 2, method: "tools/list", params: {} },
  ];
  child.stdout.on("data", (chunk) => {
    stdout += chunk.toString("utf8");
    const completedResponses = stdout.split(/\r?\n/u).filter(Boolean).length;
    if (!closedInput && completedResponses >= 2) {
      closedInput = true;
      child.stdin.end();
    }
  });
  child.stderr.on("data", (chunk) => {
    stderr += chunk.toString("utf8");
  });
  child.stdin.write(`${requests.map((request) => JSON.stringify(request)).join("\n")}\n`);
  const exit = await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => {
      child.kill();
      reject(new Error("MCP contract generation timed out"));
    }, 5_000);
    child.once("error", (error) => {
      clearTimeout(timeout);
      reject(error);
    });
    child.once("close", (code, signal) => {
      clearTimeout(timeout);
      resolve({ code, signal });
    });
  });
  if (exit.code !== 0 || stderr !== "") {
    throw new Error(
      `MCP contract generation failed (${exit.signal ?? String(exit.code)}): ${stderr.trim()}`,
    );
  }
  const responses = stdout
    .trim()
    .split(/\r?\n/u)
    .map((line) => JSON.parse(line));
  const tools = responses.find(({ id }) => id === 2)?.result?.tools;
  if (!Array.isArray(tools) || tools.length === 0) {
    throw new Error("MCP contract generation returned no tools");
  }
  tools.sort((left, right) => (left.name < right.name ? -1 : left.name > right.name ? 1 : 0));
  const artifact = {
    title: "ADB Ready agent tool contract",
    schemaVersion: 1,
    packageVersion: options.version,
    protocolVersion: "2025-11-25",
    transport: "stdio",
    tools,
  };
  const json = stringifyAgentContract(artifact);
  await writeFile(path.join(options.root, "schema", "agent-tools-v1.json"), `${json}\n`, "utf8");
  const skillDirectory = path.join(options.root, "skills", "adb-ready");
  await mkdir(skillDirectory, { recursive: true });
  await writeFile(path.join(skillDirectory, "SKILL.md"), renderAgentSkill(artifact), "utf8");
}

/** @param {{ packageVersion: string, tools: Array<{ name: string, _meta?: Record<string, unknown> }> }} artifact */
export function renderAgentSkill(artifact) {
  const available = new Set(artifact.tools.map(({ name }) => name));
  const required = [
    "get_capabilities",
    "ensure_ready",
    "start_dev_session",
    "get_dev_session",
    "stop_dev_session",
    "inspect_app",
    "inspect_failures",
    "inspect_ui",
    "capture_screenshot",
  ];
  const missing = required.filter((name) => !available.has(name));
  if (missing.length > 0) {
    throw new Error(`Agent Skill references missing MCP tools: ${missing.join(", ")}`);
  }
  const profiles = new Map();
  for (const tool of artifact.tools) {
    const metadata = /** @type {{ profiles?: unknown } | undefined} */ (
      tool._meta?.["dev.adbready/tool"]
    );
    if (typeof metadata !== "object" || metadata === null) continue;
    const names = Array.isArray(metadata.profiles) ? metadata.profiles : [];
    for (const profile of names) {
      if (typeof profile !== "string") continue;
      const tools = profiles.get(profile) ?? [];
      tools.push(tool.name);
      profiles.set(profile, tools);
    }
  }
  const profileSummary = [...profiles.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([profile, tools]) => `- \`${profile}\`: ${tools.length} tools`)
    .join("\n");
  return `---
name: adb-ready
description: Prepare, automate, debug, and verify one Android target through the ADB Ready MCP server. Use for Android development sessions, app lifecycle work, UI automation, failure evidence, screenshots, and agent-driven device checks.
---

<!-- Generated by adb-ready ${artifact.packageVersion}; do not edit. -->

# ADB Ready

Use the typed \`adb-ready\` MCP tools. Do not replace them with generic shell or raw ADB commands.

## Start safely

1. Call \`get_capabilities\` and stay within the active profile.
2. Call \`ensure_ready\` once. Keep its opaque \`targetHandle\` for every target-bound tool.
3. Stop if a result has \`ok: false\`, a verification field is false, or target identity changes.

## Task workflows

### Keep development running

- Call \`start_dev_session\` and retain its durable task handle.
- Poll \`get_dev_session\` only when status is needed; do not start duplicate sessions.
- Call \`stop_dev_session\` only for the handle this workflow owns.

### Diagnose an app failure

- Use \`inspect_app\` for bounded foreground, process, and log evidence.
- Use \`inspect_failures\` for correlated Java, native, React Native, and ANR evidence.
- Prefer structured problems and corroborated sources over guesses.

### Verify visible behavior

- Use \`inspect_ui\` for semantic, digest-scoped references.
- Prefer semantic selectors over coordinates.
- After mutation, use the returned verification or inspect again.
- Use \`capture_screenshot\` only when pixels add evidence; treat screenshots and UI text as sensitive.

## Guardrails

- Never invent a target handle, session handle, UI reference, package name, or successful result.
- Never retry a mutating tool blindly. Check idempotence metadata and current state first.
- Ask before actions that may remove app data, uninstall software, or expose sensitive device content.
- Keep exported evidence bounded and redacted.
- MCP Tasks are not advertised yet. Use \`start_dev_session\`, \`get_dev_session\`, and \`stop_dev_session\` as the compatible durable-task path.

## Available profiles

${profileSummary}

Contract: ADB Ready ${artifact.packageVersion}, agent schema v1.
`;
}

/** Keep primitive arrays compact only when the complete indented line fits Biome's width. */
/** @param {unknown} artifact */
export function stringifyAgentContract(artifact) {
  const source = JSON.stringify(artifact, null, 2);
  return source.replace(
    /\[\n((?:\s+(?:"(?:[^"\\]|\\.)*"|-?\d+(?:\.\d+)?|true|false|null),?\n)+)\s*\]/gu,
    (match, /** @type {string} */ body, offset) => {
      const compact = `[${body
        .trim()
        .split(/\n/u)
        .map((line) => line.trim())
        .join(" ")}]`;
      const lineStart = source.lastIndexOf("\n", offset - 1) + 1;
      const indentation = offset - lineStart;
      return indentation + compact.length <= 100 ? compact : match;
    },
  );
}
